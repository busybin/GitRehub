/**
 * Release editor: create a draft/full release, edit an existing one, delete it, and fill the body
 * from GitHub's generated notes.
 */
@Composable
fun ReleaseEditorScreen(
    owner: String,
    repo: String,
    releaseId: Long?,
    onDone: () -> Unit,
) {
    val vm: ReleaseEditorViewModel = viewModel()
    val state by vm.state.collectAsStateWithLifecycle()
    val busy by vm.busy.collectAsStateWithLifecycle()
    val message by vm.message.collectAsStateWithLifecycle()
    val generated by vm.generated.collectAsStateWithLifecycle()
    val savedId by vm.savedId.collectAsStateWithLifecycle()

    LaunchedEffect(owner, repo, releaseId) { vm.load(owner, repo, releaseId) }
    LaunchedEffect(savedId) { if (savedId != null) onDone() }
    val messageText = message?.render()
    LaunchedEffect(messageText) {
        if (messageText != null) {
            kotlinx.coroutines.delay(3500)
            vm.consumeMessage()
        }
    }

    AsyncContent(state = state, onRetry = { vm.load(owner, repo, releaseId) }) { data ->
        val existing = data.release
        var tag by rememberSaveable(existing?.id) { mutableStateOf(existing?.tagName.orEmpty()) }
        var target by rememberSaveable(existing?.id) { mutableStateOf(data.defaultBranch) }
        var name by rememberSaveable(existing?.id) { mutableStateOf(existing?.name.orEmpty()) }
        var body by rememberSaveable(existing?.id) { mutableStateOf(existing?.body.orEmpty()) }
        var draft by rememberSaveable(existing?.id) { mutableStateOf(existing?.draft ?: true) }
        var pre by rememberSaveable(existing?.id) { mutableStateOf(existing?.preRelease ?: false) }
        var previousTag by rememberSaveable(existing?.id) { mutableStateOf("") }
        var previousOpen by remember { mutableStateOf(false) }
        var confirmDelete by rememberSaveable { mutableStateOf(false) }

        LaunchedEffect(generated) {
            generated?.let { notes ->
                if (notes.name.isNotBlank()) name = notes.name
                body = notes.body
                vm.consumeGenerated()
            }
        }

        Column(
            Modifier
                .fillMaxWidth()
                .verticalScroll(rememberScrollState())
                .padding(16.dp),
        ) {
            if (busy) {
                LinearProgressIndicator(Modifier.fillMaxWidth())
                Spacer(Modifier.height(8.dp))
            }
            if (messageText != null) {
                Text(
                    text = messageText,
                    style = MaterialTheme.typography.bodyMedium,
                    color = if (savedId == null) MaterialTheme.colorScheme.error
                    else MaterialTheme.colorScheme.primary,
                )
                Spacer(Modifier.height(8.dp))
            }
            Text(
                text = stringResource(
                    if (existing == null) R.string.m3_release_new else R.string.m3_release_edit
                ),
                style = MaterialTheme.typography.titleLarge,
                fontWeight = FontWeight.SemiBold,
            )
            Spacer(Modifier.height(12.dp))
            OutlinedTextField(
                value = tag,
                onValueChange = { tag = it },
                label = { Text(stringResource(R.string.m3_release_tag)) },
                singleLine = true,
                modifier = Modifier.fillMaxWidth(),
            )
            Spacer(Modifier.height(10.dp))
            OutlinedTextField(
                value = target,
                onValueChange = { target = it },
                label = { Text(stringResource(R.string.m3_release_target)) },
                singleLine = true,
                modifier = Modifier.fillMaxWidth(),
            )
            Spacer(Modifier.height(10.dp))
            OutlinedTextField(
                value = name,
                onValueChange = { name = it },
                label = { Text(stringResource(R.string.m3_release_title)) },
                singleLine = true,
                modifier = Modifier.fillMaxWidth(),
            )
            Spacer(Modifier.height(10.dp))
            OutlinedTextField(
                value = body,
                onValueChange = { body = it },
                label = { Text(stringResource(R.string.m3_release_body)) },
                placeholder = { Text(stringResource(R.string.m3_release_body_hint)) },
                minLines = 10,
                modifier = Modifier.fillMaxWidth(),
            )
            Spacer(Modifier.height(10.dp))
            Row(verticalAlignment = Alignment.CenterVertically) {
                Text(
                    text = stringResource(R.string.m3_release_previous_tag),
                    style = MaterialTheme.typography.bodyMedium,
                    modifier = Modifier.weight(1f),
                )
                androidx.compose.foundation.layout.Box {
                    OutlinedButton(onClick = { previousOpen = true }) {
                        Text(previousTag.ifBlank { stringResource(R.string.m3_release_auto) })
                    }
                    DropdownMenu(expanded = previousOpen, onDismissRequest = { previousOpen = false }) {
                        DropdownMenuItem(
                            text = { Text(stringResource(R.string.m3_release_auto)) },
                            onClick = {
                                previousTag = ""
                                previousOpen = false
                            },
                        )
                        data.tags.filter { it != tag }.forEach { value ->
                            DropdownMenuItem(
                                text = { Text(value) },
                                onClick = {
                                    previousTag = value
                                    previousOpen = false
                                },
                            )
                        }
                    }
                }
            }
            Spacer(Modifier.height(4.dp))
            Row(verticalAlignment = Alignment.CenterVertically) {
                Text(
                    text = stringResource(R.string.m3_release_draft),
                    style = MaterialTheme.typography.bodyLarge,
                    modifier = Modifier.weight(1f),
                )
                Switch(checked = draft, onCheckedChange = { draft = it })
            }
            Row(verticalAlignment = Alignment.CenterVertically) {
                Text(
                    text = stringResource(R.string.m3_prerelease),
                    style = MaterialTheme.typography.bodyLarge,
                    modifier = Modifier.weight(1f),
                )
                Switch(checked = pre, onCheckedChange = { pre = it })
            }
            Spacer(Modifier.height(14.dp))
            Row(horizontalArrangement = Arrangement.spacedBy(10.dp)) {
                Button(
                    onClick = {
                        vm.save(
                            owner, repo, existing, tag, target, name, body, draft, pre,
                        )
                    },
                    enabled = !busy && tag.isNotBlank() && data.canWrite,
                ) {
                    Text(stringResource(R.string.m3_release_save))
                }
                OutlinedButton(
                    onClick = { vm.generate(owner, repo, tag, target, previousTag) },
                    enabled = !busy && tag.isNotBlank(),
                ) {
                    if (busy) {
                        CircularProgressIndicator(Modifier.width(16.dp).height(16.dp), strokeWidth = 2.dp)
                    } else {
                        Text(stringResource(R.string.m3_release_generate))
                    }
                }
            }
            if (!data.canWrite) {
                Spacer(Modifier.height(8.dp))
                Text(
                    text = stringResource(R.string.m3_edit_file_readonly_hint),
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                )
            }
            if (existing != null) {
                Spacer(Modifier.height(18.dp))
                TextButton(
                    onClick = { confirmDelete = true },
                    enabled = !busy,
                ) {
                    Text(
                        text = stringResource(R.string.m3_release_delete),
                        color = MaterialTheme.colorScheme.error,
                    )
                }
            }
        }

        if (confirmDelete && existing != null) {
            ConfirmDialog(
                title = stringResource(R.string.m3_release_delete_title, existing.title),
                message = stringResource(R.string.m3_delete_confirm_message),
                confirmLabel = stringResource(R.string.m3_release_delete),
                destructive = true,
                onConfirm = {
                    confirmDelete = false
                    vm.delete(owner, repo, existing)
                },
                onDismiss = { confirmDelete = false },
            )
        }
    }
}
